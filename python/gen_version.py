#!/usr/bin/env python3
"""Generates ``src/vs_colormatch/_version.py`` from the Cargo workspace version.

The Rust workspace version in ``Cargo.toml`` is the single authoritative version. Everything else is
derived: ``env!("CARGO_PKG_VERSION")`` in Rust, this generated file in Python, and the git tag for the
wheel. ``tests/python/test_version.py`` asserts the three agree, so drift fails the test suite rather
than shipping.

Run by ``hatch_build.py`` before the wheel is assembled; can also be run by hand::

    python3 python/gen_version.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CARGO_TOML = REPO_ROOT / "Cargo.toml"
TARGET = Path(__file__).resolve().parent / "src" / "vs_colormatch" / "_version.py"

TEMPLATE = '''"""Generated by python/gen_version.py — do not edit by hand.

The authoritative version lives in the Cargo workspace manifest.
"""

__version__ = "{version}"
version_tuple__ = ({major}, {minor}, {patch})
'''


def read_cargo_version() -> str:
    """Reads ``version`` from the ``[workspace.package]`` table of the root ``Cargo.toml``."""
    text = CARGO_TOML.read_text(encoding="utf-8")
    section = re.search(r"^\[workspace\.package\]$(.*?)(?=^\[)", text, re.MULTILINE | re.DOTALL)
    if not section:
        raise SystemExit(f"gen_version: no [workspace.package] table in {CARGO_TOML}")
    match = re.search(r'^version\s*=\s*"([^"]+)"', section.group(1), re.MULTILINE)
    if not match:
        raise SystemExit(f"gen_version: no version key in [workspace.package] of {CARGO_TOML}")
    return match.group(1)


def parse_semver(version: str) -> tuple[int, int, int]:
    """Parses ``X.Y.Z``, rejecting anything with a pre-release or build suffix."""
    match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", version)
    if not match:
        raise SystemExit(
            f"gen_version: version {version!r} is not a plain X.Y.Z. Local suffixes belong in the "
            f"git tag, not the manifest, so that the Rust, Python and wheel versions stay identical."
        )
    return int(match.group(1)), int(match.group(2)), int(match.group(3))


def main() -> int:
    version = read_cargo_version()
    major, minor, patch = parse_semver(version)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        TEMPLATE.format(version=version, major=major, minor=minor, patch=patch), encoding="utf-8"
    )
    print(f"gen_version: wrote {TARGET.relative_to(REPO_ROOT)} -> {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
